#!/usr/bin/env python3
# Generates src/util/sjis_table.cpp (CP932 double-byte -> Unicode) using Python's cp932 codec.
# Usage: python3 tools/gen_sjis.py   (run from the repository root)
vals = []
for li in range(60):
    lb = 0x81 + li if li < 31 else 0xE0 + li - 31
    for t in range(0x40, 0x100):
        try:
            c = bytes([lb, t]).decode('cp932')
            v = ord(c) if len(c) == 1 else 0
        except UnicodeDecodeError:
            v = 0
        vals.append(v)

out = ['// Generated by tools/gen_sjis.py - CP932 (Shift_JIS) to Unicode table',
       '#include "sjis.h"', 'namespace rm95 {',
       '// index: (lead-0x81 or lead-0xE0+31)*192 + (trail-0x40)',
       'static const char16_t kTable[60*192] = {']
for i in range(0, len(vals), 16):
    out.append(' ' + ','.join('0x%04x' % v for v in vals[i:i + 16]) + ',')
out.append('};')
out.append('''
char32_t sjisPairToUnicode(unsigned char lead, unsigned char trail) {
    int li;
    if (lead >= 0x81 && lead <= 0x9F) li = lead - 0x81;
    else if (lead >= 0xE0 && lead <= 0xFC) li = lead - 0xE0 + 31;
    else return 0;
    if (trail < 0x40) return 0;
    return kTable[li * 192 + (trail - 0x40)];
}
}''')
open('src/util/sjis_table.cpp', 'w').write('\n'.join(out) + '\n')
